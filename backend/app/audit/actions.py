AUDIT_ARCHIVE: Final = "AUDIT_ARCHIVE"

#: 증적 보장이 필요한 고위험 행위 — 감사 기록 실패 시 업무 트랜잭션도 롤백한다(SECURITY §5)
CRITICAL_ACTIONS: Final[frozenset[str]] = frozenset({
    LOGIN_SUCCESS, LOGIN_FAILURE, LOGOUT, PASSWORD_CHANGE, PASSWORD_RESET,
    HANDOVER_DELETE, HANDOVER_RESTORE, HANDOVER_UNDELETE,
    EXCEL_IMPORT_ROLLBACK, USER_CREATE, USER_UPDATE, ROLE_CHANGE,
    SETTING_CHANGE, BACKUP, RESTORE, AUDIT_ARCHIVE,
    # 누가 무엇을 볼 수 있는지 바꾼 기록 — 남지 않으면 권한 변경 자체를 되돌릴 수 없다
    GROUP_CREATE, GROUP_UPDATE, GROUP_MEMBER_CHANGE, GROUP_DATA_MOVE,
    HANDOVER_SCOPE_CHANGE,
    # 누가 언제 근무하는지 바꾼 기록 — 인계 누락을 따질 때 이것이 근거가 된다
    ROSTER_TEAM_CHANGE, ROSTER_OVERRIDE, ROSTER_OVERRIDE_CANCEL,
    # 누구에게 퍼졌는지 남지 않으면 '그 건을 누가 알고 있었나'를 따질 수 없다
    HANDOVER_PARTICIPANTS, HANDOVER_PROPAGATE,
    # 비밀번호를 열어 본 기록이 남지 않으면 열어 주지 않는다(기록이 이 기능의 유일한 통제다)
    CREDENTIAL_REVEAL, CREDENTIAL_REVEAL_DENIED, CREDENTIAL_DELETE,
    CREDENTIAL_VAULT_UNLOCK, CREDENTIAL_VAULT_DENIED, CREDENTIAL_VAULT_BATCH_REVEAL,
    KNOWLEDGE_DELETE, KNOWLEDGE_UPDATE,
})

ALL_ACTIONS: Final[tuple[str, ...]] = tuple(
    v for k, v in list(globals().items())
    if k.isupper() and isinstance(v, str) and k not in {"CRITICAL_ACTIONS"}
)
